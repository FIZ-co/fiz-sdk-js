// Cuts every ```ts block of README.md into test/readme/block-<n>.ts, so
// `tsc -p tsconfig.readme.json` compiles the README exactly as written, with
// the SDK's own compiler settings (noUncheckedIndexedAccess included).
//
// A block that continues an earlier one (uses `fiz`, `id`, …) gets
// declarations for those names only; nothing else is added or changed.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const out = new URL('test/readme/', root);
const readme = readFileSync(new URL('README.md', root), 'utf8');

/** Names README fragments take from the blocks before them. */
const AMBIENT = {
  fiz: 'declare const fiz: __Fiz;',
  id: 'declare const id: string;',
  draft: "declare const draft: __RequestBody<'InvoicesController_create'>;",
  order: 'declare const order: { id: string };',
  accessToken: 'declare const accessToken: string;',
};

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const blocks = [...readme.matchAll(/```ts\n([\s\S]*?)```/g)];
blocks.forEach((match, index) => {
  const code = match[1];
  const line = readme.slice(0, match.index).split('\n').length + 1;
  const declared = new Set(
    [...code.matchAll(/\b(?:const|let|var|function|class)\s+(\w+)/g)].map((m) => m[1]),
  );
  const imported = new Set(
    [...code.matchAll(/import\s+(?:type\s+)?\{([^}]*)\}/g)].flatMap((m) =>
      m[1].split(',').map((name) => name.trim().split(/\s+as\s+/).pop()),
    ),
  );
  const uses = (name) => new RegExp(`\\b${name}\\b`).test(code);
  const prelude = [
    `// README.md line ${line}. Generated by scripts/check-readme.mjs; do not edit.`,
    "import type { Fiz as __Fiz, RequestBody as __RequestBody } from '@fiz-co/sdk';",
  ];
  if (uses('Fiz') && !imported.has('Fiz')) prelude.push("import { Fiz } from '@fiz-co/sdk';");
  for (const [name, declaration] of Object.entries(AMBIENT)) {
    if (uses(name) && !declared.has(name) && !imported.has(name)) prelude.push(declaration);
  }
  prelude.push('export {};');
  writeFileSync(new URL(`block-${index}.ts`, out), `${prelude.join('\n')}\n\n${code}`);
});
console.log(`README: ${blocks.length} TypeScript blocks extracted`);
