// Generates src/generated/ from openapi/openapi.json. No network access:
// `npm run update-spec` refreshes the spec first.
//
//  - openapi.ts    — request/response types (openapi-typescript)
//  - operations.ts — operationId → method, path, and whether the route takes
//                    an Idempotency-Key. The client reads this table, so a
//                    method never restates its route by hand.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = new URL('..', import.meta.url);
const specPath = new URL('openapi/openapi.json', root);
const spec = JSON.parse(readFileSync(specPath, 'utf8'));

const HEADER =
  '// Generated by scripts/generate.mjs from openapi/openapi.json. Do not edit.\n\n';

const ast = await openapiTS(spec, {
  // Our DTOs mark properties optional unless the server always sends them;
  // keep that, do not turn every response property required.
  defaultNonNullable: false,
  exportType: true,
});
writeFileSync(
  new URL('src/generated/openapi.ts', root),
  HEADER + astToString(ast),
);

const METHODS = ['get', 'post', 'put', 'patch', 'delete'];
const operations = {};
for (const [path, item] of Object.entries(spec.paths)) {
  for (const method of METHODS) {
    const op = item[method];
    if (!op) continue;
    if (!op.operationId) throw new Error(`${method} ${path} has no operationId`);
    operations[op.operationId] = {
      method: method.toUpperCase(),
      path,
      idempotent: (op.parameters ?? []).some(
        (p) => p.in === 'header' && p.name.toLowerCase() === 'idempotency-key',
      ),
    };
  }
}
const sorted = Object.fromEntries(
  Object.entries(operations).sort(([a], [b]) => a.localeCompare(b)),
);
writeFileSync(
  new URL('src/generated/operations.ts', root),
  HEADER +
    `export const API_VERSION = ${JSON.stringify(spec.info.version)};\n\n` +
    'export const OPERATIONS = ' +
    JSON.stringify(sorted, null, 2) +
    ' as const;\n\nexport type OperationId = keyof typeof OPERATIONS;\n',
);

console.log(
  `Generated ${Object.keys(sorted).length} operations from ${fileURLToPath(specPath)}`,
);
